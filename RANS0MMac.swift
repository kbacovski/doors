private enum OutcomeKind { case scare, crucifix, thankYou }

@MainActor
private final class OutcomeOverlayManager {
    private var windows: [NSPanel] = []

    func show(_ kind: OutcomeKind) {
        close()
        for screen in NSScreen.screens {
            let window = KeyableBlackPanel(contentRect: screen.frame, styleMask: [.borderless],
                                           backing: .buffered, defer: false)
            window.isReleasedWhenClosed = false
            window.level = .screenSaver
            window.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
            window.contentView = NSHostingView(rootView: OutcomeView(kind: kind, isPrimary: screen == NSScreen.main))
            window.orderFrontRegardless()
            if screen == NSScreen.main { window.makeKey() }
            windows.append(window)
        }
        NSApp.activate(ignoringOtherApps: true)
    }

    func close() {
        windows.forEach { $0.close() }
        windows.removeAll()
    }
}

private struct OutcomeView: View {
    let kind: OutcomeKind
    let isPrimary: Bool
    @State private var vanishing = false

    var body: some View {
        ZStack {
            if kind == .thankYou {
                LinearGradient(colors: [Color(red: 0.01, green: 0.11, blue: 0.03),
                                        Color(red: 0.03, green: 0.49, blue: 0.12)],
                               startPoint: .top, endPoint: .bottom).ignoresSafeArea()
            } else {
                Color(red: kind == .scare ? 0.47 : 0.17, green: 0, blue: 0).ignoresSafeArea()
            }
            if isPrimary {
                VStack(spacing: 12) {
                    BundledImage(name: kind == .thankYou ? "ok_sign" :
                                 (kind == .scare ? "ransom_attack" : "ransom_crucifix"))
                        .frame(maxWidth: kind == .scare ? .infinity : 440,
                               maxHeight: kind == .scare ? .infinity : 520)
                        .scaleEffect(kind == .crucifix && vanishing ? 0.15 : 1)
                        .opacity(kind == .crucifix && vanishing ? 0 : 1)
                        .shadow(color: kind == .thankYou ? .green : .red, radius: 50)
                    if kind == .thankYou {
                        BundledImage(name: "thx_txt").frame(maxWidth: 600, maxHeight: 150)
                    } else if kind == .crucifix {
                        Text("REPENT")
                            .font(.system(size: 58, weight: .black, design: .monospaced))
                            .foregroundStyle(.white)
                    }
                }
                .padding(kind == .scare ? 18 : 0)
            }
        }
        .onAppear {
            if kind == .crucifix {
                withAnimation(.easeIn(duration: 2.6)) { vanishing = true }
            }
        }
    }
}

