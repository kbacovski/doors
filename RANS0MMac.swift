private enum GamePhase: Equatable {
    case ready, warning, download, ransom, crucifix, thankYou, scare, defeat, escaped, paid, expired
}

struct Coin: Identifiable {
    let id = UUID()
    let value: Int
    let drawer: Int
    let crucifix: Bool
}

@MainActor
private final class Game: ObservableObject {
    static let shared = Game()
    @Published var phase: GamePhase = .ready
    @Published var ransomAmount = 500
    @Published var duration = 90
    @Published private(set) var due = 500
    @Published private(set) var secondsLeft = 90
    @Published private(set) var warningSeconds = 3
    @Published private(set) var warningProgress = 0.0
    @Published private(set) var downloadProgress = 0.0
    @Published private(set) var coins: [Coin] = []
    @Published var selectedDrawer = 0
    @Published private(set) var collected = 0
    @Published private(set) var selectedFolderName = "Папка игры (по умолчанию)"
    @Published private(set) var coinCount = 0
    @Published private(set) var defeatSeconds = 20

    private var warningStarted = Date.distantPast
    private var downloadStarted = Date.distantPast
    private var installSoundPlayed = false
    private var ransomDeadline = Date.distantPast
    private var defeatEndsAt = Date.distantPast
    private var outcomeEndsAt = Date.distantPast
    private var nextTauntAt = Date.distantPast
    private var ticker: Timer?
    private var eventMonitor: Any?
    private var selectedFolders: [URL] = []
    private let coinStore = CoinStore()
    private let soundtrack = Soundtrack()
    private let taunts = TauntManager()
    private let ransomPanel = RansomPanelManager()
    private let defeatOverlay = DefeatOverlayManager()
    private let outcomeOverlay = OutcomeOverlayManager()
    private weak var mainWindow: NSWindow?
    private var hasAutoStarted = false

    private init() {
#if QA
        duration = 8
#endif
        let timer = Timer(timeInterval: 0.2, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.tick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        ticker = timer
    }

    func autoStartOnce() {
        guard !hasAutoStarted else { return }
        hasAutoStarted = true
        start()
    }

    func installActivityMonitor() {
        guard eventMonitor == nil else { return }
        NSApp.windows.forEach { $0.acceptsMouseMovedEvents = true }
        eventMonitor = NSEvent.addLocalMonitorForEvents(matching: [.mouseMoved, .leftMouseDragged, .rightMouseDragged, .keyDown]) { [weak self] event in
            // The game only observes input inside its own foreground window.
            if event.type == .keyDown, event.modifierFlags.contains(.command),
               event.charactersIgnoringModifiers?.lowercased() == "q" {
                NSApp.terminate(nil)
                return nil
            }
            self?.noticeActivity()
            return event
        }
    }

    func removeActivityMonitor() {
        if let eventMonitor { NSEvent.removeMonitor(eventMonitor) }
        eventMonitor = nil
    }

    func start() {
        guard phase == .ready || phase == .escaped || phase == .expired else { return }
        coinStore.cleanup()
        soundtrack.stop()
        taunts.closeAll()
        defeatOverlay.close()
        outcomeOverlay.close()
        due = ransomAmount
        secondsLeft = duration
        collected = 0
        coins = []
        coinCount = 0
        warningSeconds = 3
        warningProgress = 0
        downloadProgress = 0
        warningStarted = Date()
        phase = .warning
        Sound.play("spawn")
        updateWindowCloseButton()
    }

    func noticeActivity() {
        // Ignore the initial mouse event generated by clicking Start.
        guard phase == .warning, Date().timeIntervalSince(warningStarted) > 0.45 else { return }
        beginDownload()
    }

    func tick() {
        switch phase {
        case .warning:
            warningProgress = Date().timeIntervalSince(warningStarted) / 3
            warningSeconds = max(0, 3 - Int(Date().timeIntervalSince(warningStarted)))
#if QA
            if warningProgress >= 0.25 {
                beginDownload()
                return
            }
#endif
            if warningProgress >= 1 {
                beginDownload()
            }
        case .download:
            downloadProgress = min(1, Date().timeIntervalSince(downloadStarted) / 2.2)
            if downloadProgress >= 0.36 && !installSoundPlayed {
                installSoundPlayed = true
                Sound.play("install")
            }
            if downloadProgress >= 1 { beginRansom() }
        case .ransom:
            let now = Date()
            secondsLeft = max(0, Int(ceil(ransomDeadline.timeIntervalSince(now))))
            soundtrack.update(elapsed: duration - secondsLeft, duration: duration)
            if now >= nextTauntAt && secondsLeft > 0 {
                taunts.spawn(count: secondsLeft <= 20 ? 2 : 1)
                Sound.play("tauntSpawn")
                nextTauntAt = now.addingTimeInterval(
                    secondsLeft <= 20 ? Double.random(in: 1.5...3.0) : Double.random(in: 3.0...5.0)
                )
            }
            if secondsLeft == 0 {
                beginDefeat()
            }
        case .crucifix:
            if Date() >= outcomeEndsAt { beginThankYou() }
        case .thankYou:
            if Date() >= outcomeEndsAt { NSApp.terminate(nil) }
        case .scare:
            if Date() >= outcomeEndsAt { beginBlackout() }
        case .defeat:
            defeatSeconds = max(0, Int(ceil(defeatEndsAt.timeIntervalSinceNow)))
            if defeatSeconds == 0 {
                NSApp.terminate(nil)
            }
        default:
            break
        }
    }

    func pay(_ id: UUID) {
        guard phase == .ransom, let index = coins.firstIndex(where: { $0.id == id }) else { return }
        guard coinStore.consume(id) else { return }
        let coin = coins.remove(at: index)
        coinCount = coins.count
        if coin.crucifix {
            due = 0
            Sound.play("crucifix")
        } else {
            due = max(0, due - coin.value)
            collected += coin.value
            Sound.play("cash")
        }
        if due == 0 {
            beginVictory(crucifix: coin.crucifix)
        }
    }

    func payFile(at url: URL) {
        guard let id = coinStore.coinID(at: url) else { return }
        pay(id)
    }

    func openCoinsInFinder() { coinStore.openInFinder(all: true) }

    func chooseCoinsToPay() {
        guard phase == .ransom else { return }
        let panel = NSOpenPanel()
        panel.message = "Выбери файлы .gold или .crucifix, созданные этим раундом."
        panel.prompt = "Отдать монеты"
        panel.canChooseFiles = true
        panel.canChooseDirectories = false
        panel.allowsMultipleSelection = true
        panel.directoryURL = coinStore.currentRoot
        if panel.runModal() == .OK {
            for url in panel.urls { payFile(at: url) }
        }
    }

    func chooseFolder() {
        guard phase == .ready || phase == .escaped || phase == .expired else { return }
        let panel = NSOpenPanel()
        panel.message = "Выбери до восьми мест (например, Документы, Загрузки, Рабочий стол). В каждом появятся только разноцветные папки игры. Системную /Applications и виртуальные «Недавние» приложение не изменяет."
        panel.prompt = "Выбрать папки"
        panel.canChooseDirectories = true
        panel.canChooseFiles = false
        panel.allowsMultipleSelection = true
        if panel.runModal() == .OK, !panel.urls.isEmpty {
            let allowed = Array(panel.urls.filter { CoinStore.isAllowedRoot($0) }.prefix(8))
            if allowed.isEmpty {
                let alert = NSAlert()
                alert.messageText = "Выбери папки внутри домашней папки Mac"
                alert.informativeText = "Системные каталоги, включая /Applications, не используются. Папка «Программы» внутри твоей домашней папки подходит."
                alert.runModal()
            } else {
                selectedFolders = allowed
                selectedFolderName = allowed.map(\.lastPathComponent).joined(separator: " · ")
            }
        }
    }

    func useGameFolder() {
        selectedFolders = []
        selectedFolderName = "Папка игры (по умолчанию)"
    }

    func useStandardFolders() {
        let home = FileManager.default.homeDirectoryForCurrentUser
        let names = ["Desktop", "Documents", "Downloads", "Pictures", "Music", "Movies", "Applications"]
        selectedFolders = names.map { home.appendingPathComponent($0, isDirectory: true) }
            .filter { CoinStore.isAllowedRoot($0) && FileManager.default.fileExists(atPath: $0.path) }
        selectedFolderName = selectedFolders.isEmpty
            ? "Папка игры (по умолчанию)"
            : "\(selectedFolders.count) мест: " + selectedFolders.map(\.lastPathComponent).joined(separator: " · ")
    }

    func shutdown() {
        coinStore.cleanup()
        soundtrack.stop()
        taunts.closeAll()
        ransomPanel.close()
        defeatOverlay.close()
        outcomeOverlay.close()
        removeActivityMonitor()
        ticker?.invalidate()
    }

    private func beginDownload() {
        guard phase == .warning else { return }
        phase = .download
        downloadStarted = Date()
        installSoundPlayed = false
        downloadProgress = 0
        Sound.play("attack")
    }

    private func beginRansom() {
        guard phase == .download else { return }
        phase = .ransom
        secondsLeft = duration
        var generated: [Coin] = [Coin(value: 10, drawer: 0, crucifix: false)]
        var sum = 10
        let values = [10, 10, 10, 10, 50, 50, 50, 100, 100, 150, 200]
        while sum < Int(Double(ransomAmount) * 1.3) || generated.count < max(12, selectedFolders.count * 2) {
            let value = values.randomElement() ?? 50
            generated.append(Coin(value: value, drawer: generated.count % 6, crucifix: false))
            sum += value
        }
        generated.append(Coin(value: 0, drawer: Int.random(in: 0..<6), crucifix: true))
        if Int.random(in: 0..<3) == 0 {
            generated.append(Coin(value: 500, drawer: Int.random(in: 0..<6), crucifix: false))
        }
        let tutorial = generated.removeFirst()
        let distribution = [tutorial] + generated.shuffled()
        var placed = coinStore.scatter(distribution, in: selectedFolders)
        if placed.isEmpty && !selectedFolders.isEmpty {
            placed = coinStore.scatter(distribution, in: [])
        }
        coins = placed
        coinCount = placed.count
        due = min(ransomAmount, placed.filter { !$0.crucifix }.reduce(0) { $0 + $1.value })
        if due == 0 {
            phase = .expired
            return
        }
        ransomDeadline = Date().addingTimeInterval(TimeInterval(duration))
        nextTauntAt = Date().addingTimeInterval(3)
        selectedDrawer = Int.random(in: 0..<6)
        soundtrack.update(elapsed: 0, duration: duration)
        mainWindow = NSApp.windows.first(where: { $0.title == "doors" })
        mainWindow?.orderOut(nil)
        // The floating game panel stays visible, without a Dock icon to close.
        // Cmd+Q still terminates the foreground game through the event monitor.
        NSApp.setActivationPolicy(.accessory)
        ransomPanel.show(game: self)
        taunts.spawn(count: 5)
        Sound.play("tauntSpawn")
        coinStore.openInFinder(all: false)
#if QA
        let qaOutcome = ProcessInfo.processInfo.environment["RANS0M_QA_OUTCOME"]
        if qaOutcome == "thanks" || qaOutcome == "crucifix" {
            DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in
                guard let self, self.phase == .ransom else { return }
                if qaOutcome == "crucifix", let item = self.coins.first(where: \.crucifix) {
                    self.pay(item.id)
                } else if qaOutcome == "thanks" {
                    for item in self.coins where !item.crucifix {
                        guard self.phase == .ransom else { break }
                        self.pay(item.id)
                    }
                }
            }
        }
#endif
    }

    private func beginDefeat() {
        guard phase == .ransom else { return }
        phase = .scare
        outcomeEndsAt = Date().addingTimeInterval(3)
        coins = []
        coinCount = 0
        coinStore.cleanup()
        soundtrack.stop()
        taunts.closeAll()
        ransomPanel.close()
        Sound.play("attack")
        outcomeOverlay.show(.scare)
    }

    private func beginBlackout() {
        guard phase == .scare else { return }
        outcomeOverlay.close()
        phase = .defeat
        defeatSeconds = 20
        defeatEndsAt = Date().addingTimeInterval(20)
        defeatOverlay.show(game: self)
    }

    private func beginVictory(crucifix: Bool) {
        phase = crucifix ? .crucifix : .thankYou
        coins = []
        coinCount = 0
        coinStore.cleanup()
        soundtrack.stop()
        taunts.closeAll()
        ransomPanel.close()
        if crucifix {
            outcomeOverlay.show(.crucifix)
            outcomeEndsAt = Date().addingTimeInterval(3)
        } else {
            beginThankYou()
        }
    }

    private func beginThankYou() {
        guard phase == .crucifix || phase == .thankYou else { return }
        phase = .thankYou
        outcomeOverlay.show(.thankYou)
        outcomeEndsAt = Date().addingTimeInterval(4)
        Sound.play("thankyou")
    }

    private func updateWindowCloseButton() {
        let locked = phase == .warning || phase == .download || phase == .ransom || phase == .crucifix || phase == .thankYou || phase == .scare || phase == .defeat
        for window in NSApp.windows where window.title == "doors" {
            window.standardWindowButton(.closeButton)?.isEnabled = !locked
            window.standardWindowButton(.miniaturizeButton)?.isEnabled = !locked
        }
    }
}

private enum Sound {
    private static var active: [NSSound] = []

    static func play(_ name: String) {
        guard let path = Bundle.main.path(forResource: name, ofType: "wav"),
              let sound = NSSound(contentsOfFile: path, byReference: false) else { return }
        sound.volume = 0.22
        sound.play()
        active.removeAll(where: { !$0.isPlaying })
        active.append(sound)
    }
}

private struct BundledImage: View {
    let name: String

    var body: some View {
        Group {
            if let path = Bundle.main.path(forResource: name, ofType: "png"),
               let image = NSImage(contentsOfFile: path) {
                Image(nsImage: image).resizable().interpolation(.high).scaledToFit()
            } else {
                Image(systemName: "eye.fill").resizable().scaledToFit().foregroundStyle(Palette.red)
            }
        }
    }
}

