private final class RansomPanelManager {
    private var panel: NSPanel?

    @MainActor
    func show(game: Game) {
        close()
        let width: CGFloat = 560
        let height: CGFloat = 430
        let visible = NSScreen.main?.visibleFrame ?? NSRect(x: 0, y: 0, width: 1200, height: 800)
        let maxX = max(visible.minX, visible.maxX - width)
        let maxY = max(visible.minY, visible.maxY - height)
        let x = CGFloat.random(in: visible.minX...maxX)
        let y = CGFloat.random(in: visible.minY...maxY)
        let window = NSPanel(contentRect: NSRect(x: x, y: y, width: width, height: height),
                             styleMask: [.titled], backing: .buffered, defer: false)
        window.title = "doors — выкуп"
        window.isReleasedWhenClosed = false
        window.level = .floating
        window.hidesOnDeactivate = false
        window.isMovableByWindowBackground = true
        window.backgroundColor = NSColor(red: 0.48, green: 0.07, blue: 0.06, alpha: 1)
        window.standardWindowButton(.closeButton)?.isEnabled = false
        window.contentView = NSHostingView(rootView: RansomPanelView(game: game))
        window.makeKeyAndOrderFront(nil)
        panel = window
    }

    func close() {
        panel?.close()
        panel = nil
    }
}

